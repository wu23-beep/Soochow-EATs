# 不以 restaurant_id 硬編碼，避免不同電腦匯入 ID 不一致。
def main():
    conn = get_connection()
    try:
        needed = {'restaurants', 'menu_items', 'locations'}
        existing = {r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        if not needed.issubset(existing):
            raise RuntimeError(f"缺少資料表：{sorted(needed - existing)}，請先執行 init_db.py")

        conn.execute('BEGIN')
        inserted = 0
        skipped = 0
        missing = []
        changed_prices = []
        for shop, items in MENU.items():
            matches = conn.execute('''
                SELECT r.restaurant_id, l.campus
                FROM restaurants r JOIN locations l ON r.location_id=l.location_id
                WHERE r.restaurant_name=?
            ''', (shop,)).fetchall()
            if len(matches) != 1:
                missing.append((shop, len(matches)))
                continue
            restaurant_id = matches[0]['restaurant_id']
            for name, price in items:
                old = conn.execute('''
                    SELECT item_id, price FROM menu_items
                    WHERE restaurant_id=? AND item_name=?
                ''', (restaurant_id, name)).fetchone()
                if old:
                    skipped += 1
                    if old['price'] != price:
                        changed_prices.append((shop, name, old['price'], price))
                else:
                    conn.execute('''
                        INSERT INTO menu_items (restaurant_id,item_name,price,description,is_available)
                        VALUES (?,?,?,NULL,1)
                    ''', (restaurant_id, name, price))
                    inserted += 1
        conn.commit()
        print(f'新增菜色：{inserted} 筆；已存在略過：{skipped} 筆')
        print(f'原始整理數量：{sum(len(v) for v in MENU.values())} 筆；餐廳數：{len(MENU)} 家')
        if missing:
            print('⚠ 找不到或找到多筆同名餐廳，以下店家尚未匯入：')
            for shop, n in missing:
                print(f' - {shop}: {n} 筆同名餐廳')
        if changed_prices:
            print('⚠ 已存在品項價格與菜單不同（未覆寫）：')
            for row in changed_prices:
                print(' - %s / %s：資料庫 %s，菜單 %s' % row)
        print('本次僅收錄已辨識的菜單品項；未包含所有店家、客製化及未確認價格。')
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()

if __name__ == '__main__':
    main()
